CREATE OR ALTER TRIGGER TR_ACTUALIZAR_TOTALES_OC
ON DETALLE_ORDEN_COMPRA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @IGV_RATE DECIMAL(5,4) = 0.18;

    UPDATE OC
    SET
        SUBTOTAL = ISNULL(T.SUMA, 0),
        IGV      = ISNULL(T.SUMA, 0) * @IGV_RATE,
        TOTAL    = ISNULL(T.SUMA, 0) * (1 + @IGV_RATE)
    FROM ORDEN_COMPRA OC
    INNER JOIN (
        SELECT IDORDEN, SUM(CANTIDADPEDIDA * PRECIOUNITARIO) AS SUMA
        FROM DETALLE_ORDEN_COMPRA
        GROUP BY IDORDEN
    ) T ON OC.IDORDEN = T.IDORDEN
    WHERE OC.IDORDEN IN (
        SELECT DISTINCT IDORDEN FROM INSERTED
        UNION
        SELECT DISTINCT IDORDEN FROM DELETED
    );
END
GO

