-- =============================================================
-- TRIGGER ACTUALIZADO: TR_DESCONTAR_STOCK
-- =============================================================
CREATE OR ALTER TRIGGER TR_DESCONTAR_STOCK
ON DETALLE_VENTA
AFTER INSERT
AS
BEGIN
    SET NOCOUNT ON;

    IF EXISTS (
        SELECT 1
        FROM INSERTED I
        INNER JOIN DETALLE_PRODUCTO DP ON I.IDDETALLEPRODUCTO = DP.IDDETALLEPRODUCTO
        WHERE DP.STOCK < I.CANTIDAD
    )
    BEGIN
        RAISERROR('Stock global insuficiente para uno o más productos de la venta.', 16, 1);
        ROLLBACK TRANSACTION;
        RETURN;
    END

    IF EXISTS (
        SELECT 1
        FROM INSERTED I
        INNER JOIN LOTE L ON I.IDLOTE = L.IDLOTE
        WHERE L.STOCK_ACTUAL < I.CANTIDAD
    )
    BEGIN
        RAISERROR('Stock insuficiente en el lote seleccionado.', 16, 1);
        ROLLBACK TRANSACTION;
        RETURN;
    END

    UPDATE DP
    SET DP.STOCK = DP.STOCK - I.CANTIDAD
    FROM DETALLE_PRODUCTO DP
    INNER JOIN INSERTED I ON DP.IDDETALLEPRODUCTO = I.IDDETALLEPRODUCTO;

    UPDATE L
    SET L.STOCK_ACTUAL = L.STOCK_ACTUAL - I.CANTIDAD
    FROM LOTE L
    INNER JOIN INSERTED I ON L.IDLOTE = I.IDLOTE;
END
GO

