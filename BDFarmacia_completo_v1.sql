    CONSTRAINT PK_DETALLE_ORDEN PRIMARY KEY (IDDETALLEORDEN),
    CONSTRAINT FK_DORDEN_ORDEN
        FOREIGN KEY (IDORDEN)           REFERENCES ORDEN_COMPRA(IDORDEN),
