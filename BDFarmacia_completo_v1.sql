CREATE OR ALTER TRIGGER TR_AUMENTAR_STOCK_RECEPCION
ON DETALLE_RECEPCION
AFTER INSERT, UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE DP
    SET DP.STOCK = DP.STOCK + I.CANTIDADRECIBIDA
    FROM DETALLE_PRODUCTO DP
    INNER JOIN DETALLE_ORDEN_COMPRA DOC ON DP.IDDETALLEPRODUCTO = DOC.IDDETALLEPRODUCTO
    INNER JOIN INSERTED I               ON DOC.IDDETALLEORDEN   = I.IDDETALLEORDEN
    WHERE I.IDLOTE IS NOT NULL;

    UPDATE DOC
    SET DOC.CANTIDADRECIBIDA = DOC.CANTIDADRECIBIDA + I.CANTIDADRECIBIDA
    FROM DETALLE_ORDEN_COMPRA DOC
    INNER JOIN INSERTED I ON DOC.IDDETALLEORDEN = I.IDDETALLEORDEN
    WHERE I.IDLOTE IS NOT NULL;
END
GO

