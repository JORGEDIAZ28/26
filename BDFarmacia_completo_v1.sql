-- Vista actualizada con DP.CANTIDAD y DP.UNIDAD en lugar de PRESENTACION
CREATE OR ALTER VIEW VW_DETALLE_ORDENES AS
SELECT
    OC.NROORDEN,
    OC.ESTADO                                                AS ESTADO_ORDEN,
    P.NOMBRE                                                 AS PRODUCTO,
    M.NOMBREMARCA                                            AS MARCA,
    PR2.TIPOPRESENTACION + ' x ' +
        CAST(DP.CANTIDAD AS VARCHAR) + ' ' + DP.UNIDAD       AS PRESENTACION,
    DOC.CANTIDADPEDIDA,
    DOC.CANTIDADRECIBIDA,
    DOC.CANTIDADPEDIDA - DOC.CANTIDADRECIBIDA                AS PENDIENTE,
    DOC.PRECIOUNITARIO,
    DOC.SUBTOTAL
FROM DETALLE_ORDEN_COMPRA DOC
INNER JOIN ORDEN_COMPRA     OC   ON DOC.IDORDEN           = OC.IDORDEN
INNER JOIN DETALLE_PRODUCTO DP   ON DOC.IDDETALLEPRODUCTO = DP.IDDETALLEPRODUCTO
INNER JOIN PRODUCTO         P    ON DP.IDPRODUCTO         = P.IDPRODUCTO
INNER JOIN MARCA            M    ON DP.IDMARCA            = M.IDMARCA
INNER JOIN PRESENTACION     PR2  ON DP.IDPRESENTACION     = PR2.IDPRESENTACION
GO

CREATE OR ALTER VIEW VW_PROVEEDORES AS
SELECT
    P.IDPROVEEDOR,
    P.RUC,
    P.RAZONSOCIAL,
    P.NOMBRECOMERCIAL,
    P.CONDICIONPAGO,
    P.TELEFONO              AS TEL_EMPRESA,
    CP.NOMBRES              AS CONTACTO_PRINCIPAL,
    CP.CARGO,
    CP.CELULAR              AS CEL_CONTACTO,
    CP.CORREO               AS CORREO_CONTACTO
FROM PROVEEDOR P
LEFT JOIN CONTACTO_PROVEEDOR CP
       ON P.IDPROVEEDOR = CP.IDPROVEEDOR AND CP.PRINCIPAL = 1
WHERE P.ESTADO = 1
GO

-- Vista actualizada con DP.CANTIDAD y DP.UNIDAD
CREATE OR ALTER VIEW VW_LOTES_POR_VENCER AS
SELECT
    L.IDLOTE,
    L.NROLOTE,
    L.FECHAVENCIMIENTO,
    DATEDIFF(DAY, GETDATE(), L.FECHAVENCIMIENTO) AS DIAS_RESTANTES,
    L.STOCK_ACTUAL,
    P.NOMBRE                                     AS PRODUCTO,
    M.NOMBREMARCA                                AS MARCA,
    PR.TIPOPRESENTACION + ' x ' +
        CAST(DP.CANTIDAD AS VARCHAR) + ' ' + DP.UNIDAD AS PRESENTACION
FROM LOTE L
INNER JOIN DETALLE_PRODUCTO DP ON L.IDDETALLEPRODUCTO = DP.IDDETALLEPRODUCTO
INNER JOIN PRODUCTO         P  ON DP.IDPRODUCTO       = P.IDPRODUCTO
INNER JOIN MARCA            M  ON DP.IDMARCA          = M.IDMARCA
INNER JOIN PRESENTACION     PR ON DP.IDPRESENTACION   = PR.IDPRESENTACION
WHERE L.VIGENCIA = 1
  AND L.FECHAVENCIMIENTO <= DATEADD(DAY, 90, GETDATE())
  AND L.STOCK_ACTUAL > 0
GO

