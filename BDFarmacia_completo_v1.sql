CREATE OR ALTER VIEW VW_DEVOLUCIONES AS
SELECT
    D.IDDEVOLUCION,
    D.FECHASOLICITUD,
    D.MOTIVO,
    D.RESULTADO,
    D.OBSERVACION,
    V.IDPEDIDO                                                 AS NRO_VENTA,
    V.FECHAHORA                                                AS FECHA_VENTA,
    DATEDIFF(HOUR, V.FECHAHORA, D.FECHASOLICITUD)              AS HORAS_TRANSCURRIDAS,
    ISNULL(C.NOMBRES + ' ' + C.APELLIDOPATERNO, C.RAZONSOCIAL) AS CLIENTE,
    C.NRODOC,
    NC.NRONOTA,
    NC.MONTO,
    U.NOMBRE + ' ' + U.APELLIDOPATERNO                         AS ATENDIDO_POR
FROM DEVOLUCION D
INNER JOIN VENTA        V  ON D.IDPEDIDO     = V.IDPEDIDO
INNER JOIN CLIENTE      C  ON V.IDCLIENTE    = C.IDCLIENTE
INNER JOIN USUARIO      U  ON D.IDUSUARIO    = U.IDUSUARIO
LEFT  JOIN NOTA_CREDITO NC ON NC.IDDEVOLUCION = D.IDDEVOLUCION
GO

CREATE OR ALTER VIEW VW_CAMBIOS_REALIZADOS AS
SELECT
    CP.IDCAMBIO,
    CP.FECHACAMBIO,
    NC.NRONOTA,
    NC.MONTO                                                    AS MONTO_NOTA,
    CP.MONTO_DIFERENCIA,
    ISNULL(C.NOMBRES + ' ' + C.APELLIDOPATERNO, C.RAZONSOCIAL)  AS CLIENTE,
    P.NOMBRE                                                    AS PRODUCTO,
    M.NOMBREMARCA                                               AS MARCA,
    DC.CANTIDAD,
    DC.PRECIOUNITARIO,
    DC.CANTIDAD * DC.PRECIOUNITARIO                             AS SUBTOTAL,
    CP.IDPEDIDO_NUEVO                                           AS NUEVA_VENTA,
    U.NOMBRE + ' ' + U.APELLIDOPATERNO                          AS ATENDIDO_POR
FROM CAMBIO_PRODUCTO    CP
INNER JOIN DETALLE_CAMBIO   DC  ON CP.IDCAMBIO          = DC.IDCAMBIO
INNER JOIN NOTA_CREDITO     NC  ON CP.IDNOTACREDITO     = NC.IDNOTACREDITO
INNER JOIN DEVOLUCION       D   ON NC.IDDEVOLUCION      = D.IDDEVOLUCION
INNER JOIN VENTA            V   ON D.IDPEDIDO           = V.IDPEDIDO
INNER JOIN CLIENTE          C   ON V.IDCLIENTE          = C.IDCLIENTE
INNER JOIN DETALLE_PRODUCTO DP  ON DC.IDDETALLEPRODUCTO = DP.IDDETALLEPRODUCTO
INNER JOIN PRODUCTO         P   ON DP.IDPRODUCTO        = P.IDPRODUCTO
INNER JOIN MARCA            M   ON DP.IDMARCA           = M.IDMARCA
INNER JOIN USUARIO          U   ON CP.IDUSUARIO         = U.IDUSUARIO
GO

